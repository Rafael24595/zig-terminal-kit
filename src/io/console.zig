const std = @import("std");
const builtin = @import("builtin");

const win = std.os.windows;
const k32 = win.kernel32;

/// Hides the terminal cursor using an ANSI escape sequence.
pub const HIDE_CURSOR = "\x1b[?25l";
/// Shows the terminal cursor using an ANSI escape sequence.
pub const SHOW_CURSOR = "\x1b[?25h";

/// Clears the visible terminal screen.
pub const CLEAN_CONSOLE = "\x1B[2J";
/// Clears the terminal scrollback history when supported by the terminal.
pub const CLEAN_HISTORY = "\x1B[3J";
/// Moves the cursor to the first row and first column.
pub const RESET_CURSOR = "\x1b[H";

/// Clears the screen and scrollback history, then moves the cursor to the home position.
pub const CLEAN_ALL = CLEAN_CONSOLE ++ CLEAN_HISTORY ++ RESET_CURSOR;

/// ASCII control character generated by Ctrl+C in compatible input modes.
pub const CTRL_C: u8 = 3;

/// ASCII space character.
pub const SPACE: u8 = 0x20;
/// ASCII backspace control character.
pub const BACKSPACE: u8 = 0x08;
/// ASCII delete character.
pub const DEL: u8 = 0x7F;

const ENABLE_PROCESSED_INPUT: win.DWORD = 0x0001;
const ENABLE_LINE_INPUT: win.DWORD = 0x0002;
const ENABLE_ECHO_INPUT: win.DWORD = 0x0004;

const ENABLE_VIRTUAL_TERMINAL_PROCESSING: win.DWORD = 0x0004;

var original_termios: ?std.posix.termios = null;
var original_mode: win.DWORD = 0;

var windows_raw_mode_enabled = false;

/// Represents the dimensions of a terminal window.
pub const WinSize = struct {
    /// Number of visible columns.
    cols: usize,
    /// Number of visible rows.
    rows: usize,

    pub fn eql(self: @This(), other: WinSize) bool {
        return self.cols == other.cols and self.rows == other.rows;
    }
};

/// Enables raw-style input mode for the current terminal.
///
/// On Windows, disables line buffering, input echo, and processed input.
/// On POSIX systems, disables canonical input and echo, and configures
/// a timed read using VMIN and VTIME.
///
/// The exact behavior depends on the operating system. This function
/// must be paired with disable_raw_mode() to restore the previous settings.
pub fn enable_raw_mode() !void {
    if (builtin.os.tag == .windows) {
        return try enable_raw_mode_windows();
    }

    try enable_raw_mode_posix();
}

/// Restores the terminal input settings saved by enable_raw_mode().
///
/// Restoration errors are currently ignored by the platform-specific
/// implementations. Call this function before the application exits
/// to avoid leaving the terminal in a modified state.
pub fn disable_raw_mode() void {
    if (builtin.os.tag == .windows) {
        return disable_raw_mode_windows();
    }

    disable_raw_mode_posix();
}

fn enable_raw_mode_posix() !void {
    if (original_termios != null) {
        return;
    }

    const fd: std.posix.fd_t = std.posix.STDIN_FILENO;
    const original = try std.posix.tcgetattr(fd);

    var raw = original;

    raw.lflag.ICANON = false;
    raw.lflag.ECHO = false;
    raw.lflag.ISIG = false;

    raw.cc[@intFromEnum(std.posix.V.MIN)] = 0;
    raw.cc[@intFromEnum(std.posix.V.TIME)] = 1;

    try std.posix.tcsetattr(fd, .FLUSH, raw);

    original_termios = original;
}

fn disable_raw_mode_posix() void {
    if (original_termios) |tio| {
        _ = std.posix.tcsetattr(
            std.posix.STDIN_FILENO,
            .FLUSH,
            tio,
        ) catch return;

        original_termios = null;
    }
}

fn enable_raw_mode_windows() !void {
    const handle = k32.GetStdHandle(
        win.STD_INPUT_HANDLE,
    ) orelse return error.NoStdInput;

    var original: win.DWORD = undefined;
    if (k32.GetConsoleMode(handle, &original) == 0) {
        return error.ConsoleMode;
    }

    var mode = original;

    mode &= ~ENABLE_LINE_INPUT;
    mode &= ~ENABLE_ECHO_INPUT;
    mode &= ~ENABLE_PROCESSED_INPUT;

    if (k32.SetConsoleMode(handle, mode) == 0) {
        return error.ConsoleMode;
    }

    original_mode = original;
    windows_raw_mode_enabled = true;
}

fn disable_raw_mode_windows() void {
    if (!windows_raw_mode_enabled) {
        return;
    }

    const handle = k32.GetStdHandle(
        win.STD_INPUT_HANDLE,
    ) orelse return;

    if (k32.SetConsoleMode(handle, original_mode) != 0) {
        windows_raw_mode_enabled = false;
    }
}

/// Enables ANSI escape-sequence processing on Windows console output.
///
/// Preserves existing console mode flags.
/// Does nothing on non-Windows platforms.
pub fn enable_ansi() !void {
    if (builtin.os.tag != .windows) {
        return;
    }

    const handle = k32.GetStdHandle(
        win.STD_OUTPUT_HANDLE,
    ) orelse return error.NoStdout;

    var mode: win.DWORD = undefined;
    if (k32.GetConsoleMode(handle, &mode) == 0) {
        return error.GetConsoleModeFailed;
    }

    const new_mode = mode | ENABLE_VIRTUAL_TERMINAL_PROCESSING;
    if (new_mode == mode) {
        return;
    }

    if (k32.SetConsoleMode(handle, new_mode) == 0) {
        return error.SetConsoleModeFailed;
    }
}

/// Sets the Windows console output code page to UTF-8.
///
/// On non-Windows platforms, this function does nothing.
/// The previous code page is not restored by this module.
pub fn enable_utf8() !void {
    if (builtin.os.tag != .windows) {
        return;
    }

    if (k32.SetConsoleOutputCP(65001) == 0) {
        return error.SetConsoleOutputCPFailed;
    }
}

/// Retrieves the terminal window dimensions for supported platforms.
///
/// Returns the visible column and row counts on Windows and Linux.
/// Returns an error if the platform is unsupported, the size query fails,
/// or the reported dimensions are invalid.
pub fn winsize() !WinSize {
    if (comptime builtin.os.tag == .windows) {
        return windows_winsize();
    }

    if (comptime builtin.os.tag == .linux) {
        return linux_winsize();
    }

    return error.InvalidConsoleSize;
}

fn linux_winsize() !WinSize {
    var ws: std.posix.winsize = undefined;

    const err = std.os.linux.ioctl(
        std.posix.STDOUT_FILENO,
        std.os.linux.T.IOCGWINSZ,
        @intFromPtr(&ws),
    );

    if (err < 0) {
        return error.IoctlFailed;
    }

    const cols: usize = @intCast(ws.col);
    const rows: usize = @intCast(ws.row);

    if (rows == 0 or cols == 0) {
        return error.InvalidConsoleSize;
    }

    return WinSize{
        .cols = cols,
        .rows = rows,
    };
}

fn windows_winsize() !WinSize {
    var info: win.CONSOLE_SCREEN_BUFFER_INFO = undefined;

    const hConsole = k32.GetStdHandle(
        win.STD_OUTPUT_HANDLE,
    ) orelse return error.NoStdout;

    const ok = k32.GetConsoleScreenBufferInfo(hConsole, &info);
    if (ok == 0) {
        return error.WinAPI;
    }

    const rows: i32 =
        @as(i32, info.srWindow.Bottom) -
        @as(i32, info.srWindow.Top) + 1;

    const cols: i32 =
        @as(i32, info.srWindow.Right) -
        @as(i32, info.srWindow.Left) + 1;

    if (rows <= 0 or cols <= 0) {
        return error.InvalidConsoleSize;
    }

    return .{
        .cols = @intCast(cols),
        .rows = @intCast(rows),
    };
}

test "WinSize equality" {
    const a = WinSize{ .cols = 80, .rows = 24 };
    const b = WinSize{ .cols = 80, .rows = 24 };
    const c = WinSize{ .cols = 100, .rows = 30 };

    try std.testing.expect(a.eql(b));
    try std.testing.expect(!a.eql(c));
}
